const { db } = require('../../config/database');
const { catchAsync } = require('../../utils/catchAsync');

const ensureTable = async () => {
  await db.raw(`CREATE TABLE IF NOT EXISTS store_purchase_research (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_number varchar(50) NOT NULL UNIQUE,
  product_name varchar(255) NOT NULL,
  quantity_requested integer NOT NULL DEFAULT 1,
  reason text,
  current_stock integer DEFAULT 0,
  requested_by integer NOT NULL,
  ceo_handler integer DEFAULT NULL,
  market_handler integer DEFAULT NULL,
  ceo_instructions text DEFAULT NULL,
  research_findings text DEFAULT NULL,
  research_prices text DEFAULT NULL,
  research_suppliers text DEFAULT NULL,
  research_quality text DEFAULT NULL,
  research_availability text DEFAULT NULL,
  research_notes text DEFAULT NULL,
  research_attachments jsonb DEFAULT NULL,
  rejection_reason text DEFAULT NULL,
  approval_instructions text DEFAULT NULL,
  status citext DEFAULT 'PENDING_PURCHASE' CHECK (status IN ('PENDING_PURCHASE', 'PENDING_CEO', 'MARKET_STUDY', 'RESULTS_SUBMITTED', 'APPROVED', 'REJECTED')),
  created_at timestamp DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp DEFAULT CURRENT_TIMESTAMP
)`);
  try { await db.raw(`ALTER TABLE store_purchase_research ADD COLUMN research_prices text DEFAULT NULL`); } catch (e) {}
  try { await db.raw(`ALTER TABLE store_purchase_research ADD COLUMN research_suppliers text DEFAULT NULL`); } catch (e) {}
  try { await db.raw(`ALTER TABLE store_purchase_research ADD COLUMN research_quality text DEFAULT NULL`); } catch (e) {}
  try { await db.raw(`ALTER TABLE store_purchase_research ADD COLUMN research_availability text DEFAULT NULL`); } catch (e) {}
  try { await db.raw(`ALTER TABLE store_purchase_research ADD COLUMN research_notes text DEFAULT NULL`); } catch (e) {}
  try { await db.raw(`ALTER TABLE store_purchase_research ADD COLUMN research_attachments jsonb DEFAULT NULL`); } catch (e) {}
  try { await db.raw(`ALTER TABLE store_purchase_research ALTER COLUMN status TYPE citext;
ALTER TABLE store_purchase_research ALTER COLUMN status DROP NOT NULL;
ALTER TABLE store_purchase_research ALTER COLUMN status SET DEFAULT 'PENDING_PURCHASE'`); } catch (e) {}
};

const generateRequestNumber = () => {
  const ts = Date.now().toString(36).toUpperCase();
  const rand = Math.random().toString(36).substring(2, 6).toUpperCase();
  return `PR-${ts}-${rand}`;
};

exports.createRequest = catchAsync(async (req, res) => {
  await ensureTable();
  const { product_name, quantity_requested, reason, current_stock } = req.body;
  if (!product_name || !quantity_requested) {
    return res.status(400).json({ status: 'error', message: 'product_name and quantity_requested are required' });
  }
  const request_number = generateRequestNumber();
  const [id] = await db('store_purchase_research').insert({
    request_number,
    product_name,
    quantity_requested,
    reason: reason || null,
    current_stock: current_stock || 0,
    requested_by: req.user.id,
    status: 'PENDING_PURCHASE',
  });
  const row = await db('store_purchase_research').where('id', id).first();
  res.status(201).json({ status: 'success', data: row });
});

exports.listRequests = catchAsync(async (req, res) => {
  await ensureTable();
  const { status } = req.query;
  let q = db('store_purchase_research')
    .select(
      'store_purchase_research.*',
      'req_user.full_name as requester_name',
      'ceo_user.full_name as ceo_handler_name',
      'market_user.full_name as market_handler_name',
      db.raw('string_agg(DISTINCT roles.name::text, \', \') as requester_roles')
    )
    .leftJoin('users as req_user', 'store_purchase_research.requested_by', 'req_user.id')
    .leftJoin('users as ceo_user', 'store_purchase_research.ceo_handler', 'ceo_user.id')
    .leftJoin('users as market_user', 'store_purchase_research.market_handler', 'market_user.id')
    .leftJoin('user_roles', 'req_user.id', 'user_roles.user_id')
    .leftJoin('roles', 'user_roles.role_id', 'roles.id');
  if (status) q = q.where('store_purchase_research.status', status);
  const rows = await q.groupBy('store_purchase_research.id').orderBy('store_purchase_research.created_at', 'desc');
  res.json({ status: 'success', data: rows });
});

