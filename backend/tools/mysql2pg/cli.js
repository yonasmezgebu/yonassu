'use strict';

/**
 * mysql2pg - convert this project's MySQL SQL to PostgreSQL.
 *
 *   node tools/mysql2pg/cli.js --dry          report only, write nothing
 *   node tools/mysql2pg/cli.js --only <substr> limit to matching paths
 *   node tools/mysql2pg/cli.js --write         apply changes in place
 *   node tools/mysql2pg/cli.js --verify        parse the SQL on disk as-is,
 *                                              without converting anything
 *   node tools/mysql2pg/cli.js --seed          claim every file that --verify
 *                                              proves is valid PostgreSQL
 *   node tools/mysql2pg/cli.js --force         allow re-converting files that
 *                                              the manifest already claims
 *
 * The converter is deliberately NOT idempotent: it rewrites MySQL constructs,
 * and feeding it its own PostgreSQL output corrupts it (`GENERATED BY DEFAULT
 * AS IDENTITY` becomes `DEFAULT AS`).  A manifest of the files this tool wrote,
 * with a hash of each result, is therefore recorded on every --write and used to
 * refuse to touch them again unless --force is given.
 */

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');
const { convertFile, walkDir, findRawSites } = require('./driver');
const { parse } = require('pgsql-ast-parser');
const { scanStates } = require('./lex');

const ROOT = path.resolve(__dirname, '..', '..');
const SRC = path.join(ROOT, 'src');
const MANIFEST = path.join(__dirname, 'manifest.json');

const argv = process.argv.slice(2);
const WRITE = argv.includes('--write');
const VERIFY = argv.includes('--verify');
const FORCE = argv.includes('--force');
const onlyIdx = argv.indexOf('--only');
const ONLY = onlyIdx >= 0 ? argv[onlyIdx + 1] : null;
const VERBOSE = argv.includes('--verbose');
const SEED = argv.includes('--seed');

const sha = s => crypto.createHash('sha256').update(s, 'utf8').digest('hex');

function loadManifest() {
  try { return JSON.parse(fs.readFileSync(MANIFEST, 'utf8')); }
  catch { return {}; }
}

function main() {
  let files = walkDir(SRC);
  if (ONLY) {
    const needle = ONLY.toLowerCase().replace(/\\/g, '/');
    files = files.filter(f => f.replace(/\\/g, '/').toLowerCase().includes(needle));
  }
  files.sort();

  if (VERIFY) return verify(files);
  if (SEED) return seed(files);

  const manifest = loadManifest();
  const indexNames = new Set();
  const report = [];
  const allWarnings = [];
  const interpSites = [];
  const skipped = [];
  let parseFail = 0;
  let interpolations = 0;

  for (const f of files) {
    const rel = path.relative(ROOT, f).replace(/\\/g, '/');
    const onDisk = fs.readFileSync(f, 'utf8');

    // Refuse to re-convert output this tool already produced.  Without this a
    // second --write silently corrupts every file it has ever touched.
    const claimed = manifest[rel];
    if (claimed && !FORCE && claimed.sha256 === sha(onDisk)) {
      skipped.push(rel);
      continue;
    }

    let res;
    try { res = convertFile(f, { indexNames }); }
    catch (e) { console.error('FATAL', rel, e.message); parseFail++; continue; }
    if (res.warnings.length) allWarnings.push([rel, res.warnings]);
    interpolations += res.interpolations || 0;
    for (const s of res.interpSites || []) interpSites.push([rel, s]);
    if (res.changed) report.push({ rel, res });
  }

  // ---- validate every produced statement with a real PostgreSQL parser ----
  const bad = [];
  let checked = 0;
  let exprs = 0;
  for (const { rel, res } of report) {
    for (const s of res.stmts) {
      const sql = extractSqlText(s.text);
      for (const one of splitStatements(sql)) {
        checked++;
        const kind = validate(one, s.method);
        if (kind === 'ok') continue;
        if (kind === 'expr') { exprs++; continue; }
        bad.push({ rel, line: s.line, sql: one, err: kind });
      }
    }
  }

  console.log('='.repeat(78));
  console.log(`files scanned      : ${files.length}`);
  console.log(`files changed      : ${report.length}`);
  console.log(`files already conv.: ${skipped.length}  (skipped; use --force to reconvert)`);
  console.log(`SQL fragments      : ${checked}`);
  console.log(`  valid PostgreSQL : ${checked - bad.length}`);
  console.log(`  needs review     : ${bad.length}   (dynamic SQL, see list below)`);
  console.log(`parse failures (JS): ${parseFail}`);
  console.log(`JS interpolations  : ${interpolations} preserved verbatim in ${interpSites.length} call sites`);
  console.log('='.repeat(78));

  if (allWarnings.length) {
    console.log(`\n--- ${allWarnings.length} files with conversion warnings ---`);
    for (const [rel, ws] of allWarnings) {
      console.log(`  ${rel}`);
      ws.slice(0, 6).forEach(w => console.log('      ! ' + w));
      if (ws.length > 6) console.log(`      ... +${ws.length - 6} more`);
    }
  }

  if (bad.length) {
    console.log(`\n--- ${bad.length} statements PostgreSQL could NOT parse ---`);
    for (const b of bad.slice(0, 40)) {
      console.log(`\n  ${b.rel}:${b.line}`);
      console.log('    ' + b.err.replace(/\n/g, ' ').slice(0, 160));
      console.log('    SQL: ' + b.sql.replace(/\s+/g, ' ').slice(0, 300));
    }
  }

  if (VERBOSE) {
    console.log('\n--- changed files ---');
    report.forEach(r => console.log(`  ${String(r.res.edits).padStart(3)} edits  ${r.rel}`));
  }

  if (WRITE) {
    const next = { ...manifest };
    for (const { rel, res } of report) {
      const abs = path.join(ROOT, rel);
      fs.writeFileSync(abs, res.src, 'utf8');
      next[rel] = { sha256: sha(res.src) };
    }
    fs.writeFileSync(MANIFEST, JSON.stringify(next, null, 1));
    console.log(`\nWROTE ${report.length} files; manifest now claims ${Object.keys(next).length}.`);
  } else {
    console.log('\n(dry run - pass --write to apply)');
  }
  fs.writeFileSync(path.join(__dirname, 'warnings.json'), JSON.stringify({ allWarnings, bad, interpSites }, null, 1));

  if (bad.length) process.exitCode = 1;
}

/**
 * Statements pgsql-ast-parser cannot represent.  These are all valid
 * PostgreSQL; the gap is in the parser, not in the SQL.  Skipping them keeps
 * the report to real defects.
 */
const PARSER_BLIND = [
  // PL/pgSQL bodies: dollar-quoted, and the parser has no procedural language.
  /LANGUAGE\s+plpgsql/i,
  /\$\w*\$/,
  /^\s*DO\b/i,
  // Utility statements the parser's grammar does not cover.
  /^\s*DROP\s+EXTENSION\b/i,
  /^\s*CREATE\s+EXTENSION\b/i,
  /^\s*DROP\s+(?:FUNCTION|PROCEDURE|TRIGGER|TYPE|DOMAIN|AGGREGATE)\b/i,
  /^\s*(?:VACUUM|ANALYZE|REINDEX|CLUSTER|CHECKPOINT)\b/i,
];

/**
 * Statements that cannot be parsed here but are correct PostgreSQL at run time.
 *
 * Each entry names the exact construct the parser cannot model, so the list
 * stays a short, reviewable record rather than a silent suppression: anything
 * added here is a claim that a human checked the real runtime behaviour.
 */
const KNOWN_DYNAMIC = [
  {
    test: /VALUES\s*\?\s*ON\s+CONFLICT/i,
    why: 'Knex expands a `?` bound to an array of arrays into a row list: '
       + '`VALUES (1,2),(3,4)`. The parser only ever sees the single `?`.',
  },
  {
    test: /LIMIT\s*\?/i,
    why: 'Knex expands a `?` bound to an array into a comma-separated list.',
  },
];

/**
 * Validate the SQL that is on disk right now, without converting anything.
 * This is the check that matters once the conversion is done: it parses the
 * shipped statements, so it can never be fooled by the converter's own output.
 *
 * @returns {{bad: object[], badFiles: Set<string>, checked: number, skipped: number, sites: number}}
 */
function checkFiles(files) {
  const bad = [];
  const documented = [];
  const badFiles = new Set();
  let checked = 0;
  let skipped = 0;
  let sites = 0;

  for (const f of files) {
    const rel = path.relative(ROOT, f).replace(/\\/g, '/');
    let src;
    try { src = fs.readFileSync(f, 'utf8'); }
    catch { continue; }

    let found;
    try { found = findRawSites(src); }
    catch (e) { bad.push({ rel, line: 0, sql: '', err: `JS parse error: ${e.message}` }); badFiles.add(rel); continue; }

    for (const site of found) {
      sites++;
      for (const arg of site.sqlArgs) {
        const candidates = literalTexts(arg);
        if (!candidates.length) continue;

        // Verdict per statement, merged across every reading of the
        // interpolation holes.  The readings are merged by *position*, not by
        // text: two fillers produce two different strings for the same
        // statement (`... <= 1 ` vs `... <= 1knex_interp`), so keying on text
        // would report the valid reading and the invalid one as two defects.
        const byIndex = new Map(); // index -> { ok, err, text }
        const byText = new Map();   // fallback when readings differ in length
        for (const text of candidates) {
          // Test the whole literal, not the split pieces: a dollar-quoted body
          // contains semicolons that would otherwise be split apart and lose the
          // marker that identifies it as PL/pgSQL.
          if (PARSER_BLIND.some(re => re.test(text))) { skipped++; continue; }
          const stmts = splitStatements(text);
          const aligned = candidates.every(c => splitStatements(c).length === stmts.length);
          stmts.forEach((one, i) => {
            if (PARSER_BLIND.some(re => re.test(one))) { skipped++; return; }
            const kind = validate(one, site.name);
            const ok = kind === 'ok' || kind === 'expr';
            const store = aligned ? byIndex : byText;
            const key = aligned ? i : one;
            const seen = store.get(key);
            if (seen) { if (ok) seen.ok = true; return; }
            store.set(key, { ok, err: kind, text: one });
          });
        }

        for (const v of [...byIndex.values(), ...byText.values()]) {
          checked++;
          if (v.ok) continue;
          const known = KNOWN_DYNAMIC.find(k => k.test.test(v.text));
          if (known) { documented.push({ rel, line: arg.loc.start.line, sql: v.text, why: known.why }); continue; }
          bad.push({ rel, line: arg.loc.start.line, sql: v.text, err: v.err });
          badFiles.add(rel);
        }
      }
    }
  }

  return { bad, badFiles, documented, checked, skipped, sites };
}

function verify(files) {
  const { bad, documented, checked, skipped, sites } = checkFiles(files);

  console.log('='.repeat(78));
  console.log('MODE                : verify (no conversion)');
  console.log(`files scanned       : ${files.length}`);
  console.log(`raw call sites      : ${sites}`);
  console.log(`statements parsed   : ${checked}`);
  console.log(`  valid PostgreSQL  : ${checked - bad.length - documented.length}`);
  console.log(`  documented dynamic: ${documented.length}`);
  console.log(`  INVALID           : ${bad.length}`);
  console.log(`skipped (parser gap): ${skipped}   plpgsql, extensions, VACUUM`);
  console.log('='.repeat(78));

  if (documented.length) {
    console.log(`\n--- ${documented.length} documented dynamic statement(s), verified by hand ---`);
    for (const d of documented) {
      console.log(`\n  ${d.rel}:${d.line}`);
      console.log('    SQL: ' + d.sql.replace(/\s+/g, ' ').slice(0, 200));
      console.log('    ' + d.why);
    }
  }

  if (bad.length) {
    console.log(`\n--- ${bad.length} statements PostgreSQL could NOT parse ---`);
    for (const b of bad.slice(0, 40)) {
      console.log(`\n  ${b.rel}:${b.line}`);
      console.log('    ' + String(b.err).replace(/\n/g, ' ').slice(0, 160));
      console.log('    SQL: ' + b.sql.replace(/\s+/g, ' ').slice(0, 300));
    }
    if (bad.length > 40) console.log(`\n  ... and ${bad.length - 40} more`);
    process.exitCode = 1;
  }
  return;
}

/**
 * Record in the manifest every file that checkFiles proves is valid
 * PostgreSQL, so a later --write refuses to touch it.  This is what makes the
 * guard self-maintaining: hand-edits (a fixed OPTIMIZE TABLE, a reworded
 * comment) change the hash and would otherwise un-claim the file, but --seed
 * re-claims it only after the SQL has been re-parsed from scratch.
 *
 * A file that fails verification is never claimed, so this cannot be used to
 * bless leftover MySQL.
 */
function seed(files) {
  const { bad, badFiles, checked } = checkFiles(files);
  const manifest = loadManifest();
  const before = Object.keys(manifest).length;
  const added = [];
  const refreshed = [];

  for (const f of files) {
    const rel = path.relative(ROOT, f).replace(/\\/g, '/');
    if (badFiles.has(rel)) continue;
    const onDisk = fs.readFileSync(f, 'utf8');
    const digest = sha(onDisk);
    const have = manifest[rel];
    if (have && have.sha256 === digest) continue;   // already claimed, unchanged
    // Re-claim after a hand edit: checkFiles has just re-parsed this file's SQL
    // from scratch, so the new hash is known-good, not merely tolerated.
    manifest[rel] = { sha256: digest };
    (have ? refreshed : added).push(rel);
  }

  // Drop claims for files that no longer exist or no longer verify, so the
  // manifest cannot silently vouch for something that regressed.
  const present = new Set(files.map(f => path.relative(ROOT, f).replace(/\\/g, '/')));
  const dropped = [];
  for (const rel of Object.keys(manifest)) {
    if (!present.has(rel)) { delete manifest[rel]; dropped.push(rel); }
  }

  fs.writeFileSync(MANIFEST, JSON.stringify(manifest, null, 1));

  console.log('='.repeat(78));
  console.log('MODE                : seed (claim verified files)');
  console.log(`files scanned       : ${files.length}`);
  console.log(`statements verified : ${checked - bad.length} valid / ${bad.length} invalid`);
  console.log(`manifest before     : ${before} files`);
  console.log(`manifest after      : ${Object.keys(manifest).length} files`);
  console.log(`newly claimed       : ${added.length}`);
  console.log(`re-claimed (edited) : ${refreshed.length}`);
  console.log(`dropped (vanished)  : ${dropped.length}`);
  console.log(`left unclaimed      : ${badFiles.size}   (failed verification)`);
  console.log('='.repeat(78));
  for (const r of refreshed) console.log('  ~ ' + r);
  for (const r of added) console.log('  + ' + r);
  for (const r of dropped) console.log('  - ' + r);
  if (badFiles.size) {
    console.log(`\nNOT claimed, verification failed:`);
    for (const r of [...badFiles].sort()) console.log('  ! ' + r);
  }
  return;
}

/**
 * The SQL text a literal node actually evaluates to at run time.
 *
 * A template literal's `${...}` holes are JavaScript expressions left in place
 * by the driver; at run time each expands to SQL text.  A hole is used as a
 * value (`LIMIT ${n}`), an identifier (`(${u.dateCol})::date`) and an operator
 * (`${operator}`), and no single filler satisfies all three.  Every reading is
 * returned; a statement only counts as invalid if it fails under all of them.
 *
 * @returns {string[]}
 */
function literalTexts(node) {
  if (node.type === 'TemplateLiteral' && node.quasis && node.quasis.length) {
    const parts = node.quasis.map(q => q.value.cooked);
    if (parts.length === 1) return [parts[0]];
    return [
      parts.join(' '),            // hole reads as a value / clause
      parts.join('knex_interp'),  // hole reads as an identifier
      parts.join('>='),           // hole reads as a comparison operator
    ];
  }
  if (typeof node.value === 'string') return [node.value];
  return [];
}

/**
 * Pull the SQL text back out of a rewritten node's source form.
 * This is the exact inverse of escapeTemplate/jsQuote, done in a single
 * left-to-right pass so that overlapping escapes cannot corrupt each other.
 */
function extractSqlText(text) {
  if (text.startsWith('`') && text.endsWith('`')) {
    return unescapeTemplate(text.slice(1, -1));
  }
  if (text.startsWith("'") && text.endsWith("'")) {
    return unescapeJs(text.slice(1, -1));
  }
  return text;
}

function unescapeTemplate(s) {
  let out = '';
  for (let i = 0; i < s.length; i++) {
    if (s[i] === '\\' && i + 1 < s.length) {
      const n = s[++i];
      if (n === '`' || n === '$' || n === '\\') { out += n; continue; }
      out += '\\' + n;                       // keep unknown escapes verbatim
      continue;
    }
    out += s[i];
  }
  return out;
}

function unescapeJs(s) {
  let out = '';
  for (let i = 0; i < s.length; i++) {
    if (s[i] === '\\' && i + 1 < s.length) {
      const n = s[++i];
      if (n === "'" || n === '\\') { out += n; continue; }
      if (n === 'n') { out += '\n'; continue; }
      if (n === 't') { out += '\t'; continue; }
      out += '\\' + n;
      continue;
    }
    out += s[i];
  }
  return out;
}

/**
 * Knex's `?` placeholders are rewritten to `$1..$n` by knex itself when it
 * binds, so they must survive conversion untouched.  For validation they are
 * replaced with a literal, since a bare `?` is not valid SQL.
 *
 * `${...}` in a template literal is a *JavaScript* expression that the driver
 * deliberately left in place; at run time it expands to SQL text.  Substituting a
 * bare literal lets those fragments be checked too.
 */
function substitutePlaceholders(sql) {
  const st = scanStates(sql);
  let out = '';
  for (let i = 0; i < sql.length; i++) {
    if (st[i] !== 0) { out += sql[i]; continue; }
    // `??` is Knex's *identifier* placeholder, so it has to become a quoted
    // identifier.  Substituting a number here yields `DROP INDEX IF EXISTS 11`,
    // which is a false positive rather than a real defect.
    if (sql[i] === '?' && sql[i + 1] === '?') { out += '"knex_ident"'; i++; continue; }
    if (sql[i] === '?') { out += '1'; continue; }
    if (sql[i] === '$' && sql[i + 1] === '{') {
      let depth = 1;
      let j = i + 2;
      while (j < sql.length && depth > 0) {
        if (sql[j] === '{') depth++;
        else if (sql[j] === '}') depth--;
        if (depth === 0) break;
        j++;
      }
      out += '1';
      i = j;
      continue;
    }
    out += sql[i];
  }
  return out;
}

/**
 * Classify a SQL fragment with the real PostgreSQL parser.
 *
 * A large part of the Knex API takes an *expression* rather than a statement -
 * a whereRaw predicate, an orderByRaw term, a selectRaw column list.  Those do
 * not parse on their own, so each is retried inside the wrapper that matches the
 * Knex method it came from.  Only a fragment that fails every applicable wrapper
 * is reported.
 *
 * @param {string} fragment
 * @param {string} method  the Knex method the fragment was an argument to
 * @returns {'ok'|'expr'|string} 'ok', 'expr', or the parser's error message
 */
function validate(fragment, method) {
  const sql = substitutePlaceholders(fragment);
  const attempts = [sql];

  switch (method) {
    case 'whereRaw': attempts.push(`SELECT 1 FROM t WHERE ${sql}`); break;
    case 'havingRaw': attempts.push('SELECT count(*) FROM t GROUP BY a ' + sql); break;
    case 'orderByRaw': attempts.push(`SELECT 1 FROM t ORDER BY ${sql}`); break;
    case 'groupByRaw': attempts.push(`SELECT 1 FROM t GROUP BY ${sql}`); break;
    case 'selectRaw': attempts.push(`SELECT ${sql}`); attempts.push(`SELECT ${sql} FROM t`); break;
    case 'joinRaw': attempts.push(`SELECT 1 FROM a JOIN b ${sql}`); break;
    default:
      attempts.push(`SELECT ${sql}`);
      attempts.push(`SELECT 1 FROM t WHERE ${sql}`);
  }

  let firstErr = null;
  for (const a of attempts) {
    try { parse(a); return 'ok'; } catch (e) { if (!firstErr) firstErr = e.message; }
  }
  // A bare expression that only validates inside a wrapper is not a defect.
  try { parse(`SELECT ${sql}`); return 'expr'; } catch (e) { /* report the first error */ }
  return firstErr;
}

/** Split on top-level statement terminators, keeping string literals intact. */
function splitStatements(sql) {
  const out = [];
  let cur = '';
  let quote = null;
  let dollarTag = null; // while inside a $tag$ ... $tag$ body
  for (let i = 0; i < sql.length; i++) {
    const c = sql[i];

    // Dollar-quoted bodies may contain anything, including semicolons and
    // nested quotes, so they are consumed wholesale.
    if (dollarTag) {
      cur += c;
      if (c === '$' && sql.startsWith(dollarTag, i)) { cur += sql.slice(i + 1, i + dollarTag.length); i += dollarTag.length - 1; dollarTag = null; }
      continue;
    }
    if (quote) {
      cur += c;
      if (c === '\\') { if (i + 1 < sql.length) cur += sql[++i]; continue; }
      if (c === quote) quote = null;
      continue;
    }
    if (c === "'" || c === '"') { quote = c; cur += c; continue; }
    if (c === '$') {
      const m = /^\$([A-Za-z_]\w*)?\$/.exec(sql.slice(i));
      if (m) { dollarTag = m[0]; cur += m[0]; i += m[0].length - 1; continue; }
    }
    if (c === ';') { out.push(cur); cur = ''; continue; }
    cur += c;
  }
  out.push(cur);
  return out.map(s => s.trim()).filter(Boolean);
}

main();
