'use strict';

/**
 * Unit tests for the MySQL -> PostgreSQL converter.
 *   node tools/mysql2pg/selftest.js
 * Each case asserts on substrings that MUST be present / MUST be absent, so
 * the test states the intent rather than the exact formatting.
 */

const { convertSql } = require('./convert');
const { parse } = require('pgsql-ast-parser');

let pass = 0, fail = 0;
const failures = [];

function t(name, input, must, mustNot) {
  let out;
  try { out = convertSql(input, { indexNames: new Set(), warnings: [] }).join('\n'); }
  catch (e) { fail++; failures.push(`${name}\n    THREW ${e.message}`); return; }

  const problems = [];
  for (const m of [].concat(must || [])) {
    if (!out.includes(m)) problems.push(`missing: ${JSON.stringify(m)}`);
  }
  for (const m of [].concat(mustNot || [])) {
    if (out.includes(m)) problems.push(`must not contain: ${JSON.stringify(m)}`);
  }
  if (problems.length) {
    fail++; failures.push(`${name}\n${problems.map(p => '    ' + p).join('\n')}\n    --- got ---\n${indent(out)}`);
  } else { pass++; }
}

/** Sanity check: is the result at least syntactically valid PostgreSQL? */
function tp(name, input) {
  let out;
  try { out = convertSql(input, { indexNames: new Set(), warnings: [] }).join('\n'); }
  catch (e) { fail++; failures.push(`${name}\n    THREW ${e.message}`); return; }
  for (const stmt of out.split(/;\s*\n/)) {
    const s = stmt.replace(/;\s*$/, '').trim();
    if (!s) continue;
    try { parse(s); }
    catch (e) {
      fail++;
      failures.push(`${name}\n    PG PARSE: ${e.message}\n    --- got ---\n${indent(out)}`);
      return;
    }
  }
  pass++;
}

/** Exact-occurrence assertion. Use where a substring may legitimately appear
 *  more than once and the count itself is the thing under test. */
function tcount(name, input, needle, expected) {
  let out;
  try { out = convertSql(input, { indexNames: new Set(), warnings: [] }).join('\n'); }
  catch (e) { fail++; failures.push(`${name}\n    THREW ${e.message}`); return; }
  const n = out.split(needle).length - 1;
  if (n !== expected) {
    fail++;
    failures.push(`${name}\n    expected ${expected} x ${JSON.stringify(needle)}, got ${n}`
      + `\n    --- got ---\n${indent(out)}`);
  } else { pass++; }
}

const indent = s => String(s).split('\n').map(l => '      ' + l).join('\n');

