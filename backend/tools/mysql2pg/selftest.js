t('create table: types',
  `CREATE TABLE \`t\` (
     \`id\` int(11) NOT NULL AUTO_INCREMENT,
     \`big\` bigint(20) unsigned DEFAULT NULL,
     \`flag\` tinyint(1) NOT NULL DEFAULT '0',
     \`small\` tinyint(4) DEFAULT NULL,
     \`amount\` decimal(10,2) NOT NULL DEFAULT '0.00',
     \`data\` json DEFAULT NULL,
     \`body\` longtext,
     \`ts\` datetime DEFAULT CURRENT_TIMESTAMP,
     \`up\` timestamp NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,
     \`label\` enum('A','b','C') NOT NULL DEFAULT 'A',
     \`file\` blob,
     PRIMARY KEY (\`id\`)
   ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4`,
  ['id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL',
    'big bigint',
    'flag boolean NOT NULL DEFAULT false',
    'small smallint',
    'amount numeric(10,2)',
    'data jsonb',
    'body text',
    'ts timestamp DEFAULT CURRENT_TIMESTAMP',
    'up timestamp',
    'label citext',
    'file bytea',
    'PRIMARY KEY (id)'],
  ['AUTO_INCREMENT', 'unsigned', 'int(11)', 'ENGINE=', 'longtext', 'ON UPDATE', 'blob']);

t('create table: enum check constraint',
  `CREATE TABLE \`t\` (\`id\` int, \`st\` enum('open','Closed') DEFAULT 'open')`,
  [`CHECK (st IN ('open', 'Closed'))`]);

// MySQL lets a foreign key be unnamed; PostgreSQL does not.  These dumps are
// full of bare `FOREIGN KEY (...) REFERENCES ...`, which once produced a
// constraint literally called "null".
t('create table: unnamed foreign key gets a generated name',
  'CREATE TABLE `t` (`id` int, `parent_id` int, FOREIGN KEY (`parent_id`) REFERENCES `p` (`id`) ON DELETE CASCADE)',
  ['CONSTRAINT t_fk_parent_id FOREIGN KEY (parent_id) REFERENCES p (id) ON DELETE CASCADE'],
  ['"null"', 'CONSTRAINT null']);
tp('create table: unnamed foreign key', 'CREATE TABLE `t` (`id` int, `parent_id` int, FOREIGN KEY (`parent_id`) REFERENCES `p` (`id`))');

t('create table: named foreign key keeps its name',
  'CREATE TABLE `t` (`id` int, `parent_id` int, CONSTRAINT `fk_t_parent` FOREIGN KEY (`parent_id`) REFERENCES `p` (`id`))',
  ['CONSTRAINT fk_t_parent FOREIGN KEY'], ['"null"']);

// A constraint and the index supporting it may share a name: PostgreSQL keeps
// constraint and index names in separate namespaces.  Sharing one name pool
// renamed the index to "..._2" for no reason.
tcount('create table: FK index is not renamed away from its constraint',
  'CREATE TABLE `t` (`id` int, `parent_id` int, FOREIGN KEY (`parent_id`) REFERENCES `p` (`id`))',
  '_2', 0);

// A single-column inline PRIMARY KEY is legal and must survive untouched.
tcount('create table: inline-only primary key is preserved',
  'CREATE TABLE `t` (`id` int UNSIGNED AUTO_INCREMENT PRIMARY KEY, `x` int)',
  'PRIMARY KEY', 1);

// exactly one PRIMARY KEY.  Marking the column itself primary as well yields a
// table that PostgreSQL refuses with "multiple primary keys".
tcount('create table: AUTO_INCREMENT does not add a second PRIMARY KEY',
  'CREATE TABLE `t` (`id` int(11) NOT NULL AUTO_INCREMENT, PRIMARY KEY (`id`))',
  'PRIMARY KEY', 1);
t('create table: AUTO_INCREMENT keeps its identity column',
  'CREATE TABLE `t` (`id` int(11) NOT NULL AUTO_INCREMENT, PRIMARY KEY (`id`))',
  ['GENERATED BY DEFAULT AS IDENTITY'], ['PRIMARY KEY (`id`)']);

// AUTO_INCREMENT only demands *some* key, so an inline UNIQUE is a legal and
// sufficient replacement.
tcount('create table: AUTO_INCREMENT plus inline UNIQUE',
  "CREATE TABLE `t` (`id` int(11) NOT NULL AUTO_INCREMENT, `id` int UNIQUE)",
  'PRIMARY KEY', 0);

// PostgreSQL has no `ALTER TABLE ... ADD INDEX`; an index is a separate object.
t('alter table: ADD UNIQUE INDEX becomes CREATE UNIQUE INDEX',
  'ALTER TABLE `product_tax_mappings` ADD UNIQUE INDEX `uq_mapping_source_item` (`source`, `item_id`)',
  ['CREATE UNIQUE INDEX uq_mapping_source_item ON product_tax_mappings (source, item_id)'],
  ['ADD UNIQUE INDEX']);
tp('alter table: ADD UNIQUE INDEX', 'ALTER TABLE `t` ADD UNIQUE INDEX `uq_a` (`a`, `b`)');

t('alter table: ADD KEY becomes CREATE INDEX',
  'ALTER TABLE `t` ADD KEY `idx_a` (`a`)',
  ['CREATE INDEX idx_a ON t (a)'], ['ADD KEY']);
tp('alter table: ADD KEY', 'ALTER TABLE `t` ADD KEY `idx_a` (`a`)');

t('create table: NOT NULL and DEFAULT are not word-split',
  `CREATE TABLE \`t\` (
     \`a\` varchar(50) NOT NULL DEFAULT 'x y z',
     \`b\` int NOT NULL DEFAULT 10,
     \`c\` text NULL
   )`,
  [`a varchar(50) NOT NULL DEFAULT 'x y z'`, 'b integer NOT NULL DEFAULT 10', 'c text NULL']);

t('create table: index extraction + naming',
  `CREATE TABLE \`users\` (
     \`id\` int NOT NULL AUTO_INCREMENT,
     \`email\` varchar(255) NOT NULL,
     \`phone\` varchar(20) DEFAULT NULL,
     PRIMARY KEY (\`id\`),
     UNIQUE KEY \`email\` (\`email\`),
     KEY \`idx_users_phone\` (\`phone\`)
   )`,
  ['CREATE UNIQUE INDEX IF NOT EXISTS users_email ON users (email)',
    'CREATE INDEX IF NOT EXISTS users_idx_users_phone ON users (phone)'],
  ['UNIQUE KEY']);

t('create table: FK gets an index even when MySQL left it implicit',
  `CREATE TABLE \`orders\` (
     \`id\` int NOT NULL AUTO_INCREMENT,
     \`user_id\` int NOT NULL,
     PRIMARY KEY (\`id\`),
     CONSTRAINT \`fk_ou\` FOREIGN KEY (\`user_id\`) REFERENCES \`users\` (\`id\`) ON DELETE CASCADE
   )`,
  ['CREATE INDEX IF NOT EXISTS orders_fk_user_id ON orders (user_id)',
    'FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE']);

t('create table: fk index is not duplicated when already indexed',
  `CREATE TABLE \`orders\` (
     \`id\` int NOT NULL,
     \`user_id\` int NOT NULL,
     \`department_id\` int NOT NULL,
     PRIMARY KEY (\`id\`),
     KEY \`user_id\` (\`user_id\`),
     KEY \`department_id\` (\`department_id\`),
     CONSTRAINT \`fk_a\` FOREIGN KEY (\`user_id\`) REFERENCES \`users\` (\`id\`),
     CONSTRAINT \`fk_b\` FOREIGN KEY (\`department_id\`) REFERENCES \`departments\` (\`id\`)
   )`,
  ['CREATE INDEX IF NOT EXISTS orders_user_id ON orders (user_id)'],
  ['orders_fk_user_id', 'orders_fk_department_id']);

t('create table: mysql prefix index becomes an expression index',
  `CREATE TABLE \`t\` (\`id\` int, \`name\` varchar(255), KEY \`k\` (\`name\`(20)))`,
  ['left(name, 20)']);

t('create table: if not exists preserved',
  'CREATE TABLE IF NOT EXISTS `t` (`id` int)',
  ['CREATE TABLE IF NOT EXISTS t (']);

t('double-quoted MySQL string literals become single-quoted',
  'SELECT * FROM `t` WHERE `role` = "Admin"',
  ["role = 'Admin'"]);

t('double quotes INSIDE a single-quoted JSON value are left alone',
  "INSERT INTO `t` (`roles`) VALUES ('[\"Admin\",\"User\"]')",
  ['VALUES (\'["Admin","User"]\')'],
  ["'[Admin", "'Admin"]);

// A MySQL "double-quoted identifier" is indistinguishable from a string literal
// by shape alone, so the converter treats it as data and records a warning for
// review.  The audit of all 24 affected files found only genuine string values
// ("Admin", "%Y-%m", "192.168.%"), but the warning list is the safety net.
t('ambiguous double-quoted token is treated as data and reported',
  'SELECT `a` AS "Mixed_Case" FROM `t`',
  ["a AS 'Mixed_Case'"]);

t('placeholder markers survive the pipeline',
  'SELECT * FROM `t` WHERE `a` = ? AND `b` = ?',
  ['a = ?', 'b = ?']);

t('knex ? placeholders are left for knex to bind',
  "INSERT INTO `t` (`a`) VALUES (?) ON CONFLICT DO NOTHING",
  ['VALUES (?)', 'ON CONFLICT DO NOTHING']);

t('zero-argument calls are detected', // NOW() yields args === [''], not []
  'SELECT NOW(), CURDATE(), UUID()',
  ['LOCALTIMESTAMP', 'CURRENT_DATE', 'gen_random_uuid()'],
  ['NOW()', 'CURDATE()', 'UUID()']);

