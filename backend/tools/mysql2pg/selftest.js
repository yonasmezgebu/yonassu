t('database() -> current_schema()',
  'SELECT * FROM information_schema.TABLES WHERE table_schema = DATABASE()',
  ['current_schema()'],
  ['DATABASE()']);

t('data_length -> relation size',
  'SELECT (data_length + index_length) FROM information_schema.TABLES',
  ['pg_total_relation_size'],
  ['data_length', 'index_length']);

// Regression: the size rewrite matches the parentheses too, so it has to put
// them back.  Otherwise `SUM(data_length + index_length)` loses SUM's opening
// paren and becomes `SUMpg_total_relation_size(...)` - which still parses as a
// call to a function with a bogus name, so only a textual check catches it.
t('SUM(data_length + index_length) keeps SUM parens',
  'SELECT SUM(data_length + index_length) AS size FROM information_schema.tables',
  ['SUM(pg_total_relation_size'],
  ['SUMpg_total_relation_size']);

t('ROUND(SUM(data_length + index_length)) keeps both parens',
  'SELECT ROUND(SUM(data_length + index_length) / 1024 / 1024, 1) AS size_mb FROM information_schema.tables',
  ['ROUND(SUM(pg_total_relation_size'],
  ['ROUNDSUM', 'SUMpg_total_relation_size']);

