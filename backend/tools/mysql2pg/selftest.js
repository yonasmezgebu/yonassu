t('backtick identifiers requoted to bare/double-quoted',
  'SELECT `u`.`name`, `total` FROM `users` u WHERE `u`.`id` = ?',
  ['SELECT u.name, total FROM users u WHERE u.id = ?'],
  ['`']);

t('reserved-word identifiers stay double-quoted',
  'SELECT `default`, `null`, `user`, `order` FROM `t`',
  ['"default"', '"null"', '"user"', '"order"']);

t('date functions',
  'SELECT DATE_ADD(`d`, INTERVAL 7 DAY), DATE_SUB(`d`, INTERVAL 1 MONTH), CURDATE()',
  ["(d) + INTERVAL '7 days'", "(d) - INTERVAL '1 month'", 'CURRENT_DATE'],
  ['DATE_ADD(', 'DATE_SUB(', 'INTERVAL 7 DAY', 'CURDATE(']);

t('timestampdiff day is exact whole days',
  'SELECT TIMESTAMPDIFF(DAY, `a`, `b`) FROM `t`',
  ['((b)::date - (a)::date)']);

t('timestampdiff second uses epoch',
  'SELECT TIMESTAMPDIFF(SECOND, `a`, `b`) FROM `t`',
  ['EXTRACT(EPOCH FROM ((b)::timestamp - (a)::timestamp)) / 1']);

t('mysql string functions',
  'SELECT CONCAT(`a`, \'-\', `b`), CONCAT_WS(\',\', `a`, `b`), LOCATE(\'x\', `a`)',
  ["a::text || '-' || b::text", "concat_ws(',', a::text, b::text)", "strpos(a, 'x')"]);

t('group_concat',
  'SELECT GROUP_CONCAT(DISTINCT `x` ORDER BY `x` SEPARATOR ", ") FROM `t`',
  ["string_agg(DISTINCT x::text, ', ' ORDER BY x::text)"]);

t('group_concat without distinct or order',
  'SELECT GROUP_CONCAT(`x`) FROM `t`',
  ["string_agg(x::text, ', ')"]);

t('if() -> case when',
  'SELECT IF(`a` > 1, \'big\', \'small\')',
  ["CASE WHEN (a > 1) THEN ('big') ELSE ('small') END"],
  ['IF(']);

t('ifnull/coalesce and nullif',
  'SELECT IFNULL(`a`, 0), COALESCE(`b`, 1), NULLIF(`c`, 0)',
  ['COALESCE(a, 0)', 'COALESCE(b, 1)', 'NULLIF(c, 0)']);

t('limit with offset',
  'SELECT * FROM `t` LIMIT 10, 20',
  ['LIMIT 20 OFFSET 10'],
  ['LIMIT 10, 20']);

t('insert ignore -> on conflict',
  'INSERT IGNORE INTO `t` (`a`) VALUES (?)',
  ['ON CONFLICT DO NOTHING'],
  ['INSERT IGNORE']);

t('truncate gets explicit TABLE',
  'TRUNCATE `t`',
  ['TRUNCATE TABLE t']);

t('regexp operator',
  "SELECT * FROM `t` WHERE `name` RLIKE '^a'",
  ["~ '^a'"],
  ['RLIKE']);

t('cast as char',
  'SELECT CAST(`a` AS CHAR(10)), CAST(`b` AS CHAR)',
  ['CAST(a AS VARCHAR(10))', 'CAST(b AS TEXT)']);

